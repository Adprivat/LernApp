/**
 * One-time script: reads questions.json and generates SQL INSERT statements.
 * Run: node scripts/generate-seed-sql.js
 * Output: supabase/migrations/20260406000001_seed_questions.sql
 */
const fs = require('fs');
const path = require('path');

const jsonPath = path.join(__dirname, '..', 'src', 'data', 'questions.json');
const outPath = path.join(__dirname, '..', 'supabase', 'migrations', '20260406000001_seed_questions.sql');

const data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));

function escapeSql(str) {
  return str.replace(/'/g, "''");
}

function toSqlArray(arr) {
  const escaped = arr.map(s => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`);
  return `'{${escaped.join(',')}}'`;
}

let sql = `-- ============================================================
-- Seed: ${data.categories.exam_prep.questions.length} questions from questions.json
-- Generated by scripts/generate-seed-sql.js
-- ============================================================

`;

const questions = data.categories.exam_prep.questions;

sql += `insert into public.questions (category_id, question, answers, correct_index, difficulty, tags, sort_order)\nvalues\n`;

const rows = questions.map((q, i) => {
  const question = escapeSql(q.question);
  const answers = `ARRAY[${q.answers.map(a => `'${escapeSql(a)}'`).join(', ')}]`;
  const tags = q.tags && q.tags.length > 0
    ? `ARRAY[${q.tags.map(t => `'${escapeSql(t)}'`).join(', ')}]::text[]`
    : `'{}'::text[]`;
  return `  ((select id from public.question_categories where key = 'exam_prep'), '${question}', ${answers}, ${q.correct_index}, '${q.difficulty}', ${tags}, ${i})`;
});

sql += rows.join(',\n') + ';\n';

fs.writeFileSync(outPath, sql, 'utf8');
console.log(`Generated ${questions.length} question inserts -> ${outPath}`);
